CREATE OR REPLACE VIEW v_ekko AS
SELECT
    EBELN,
    BUKRS,
    BSTYP,
    BSART,
    LOEKZ,
    TRY_CAST(AEDAT AS DATE) AS AEDAT,
    ERNAM,
    LIFNR,
    ZTERM,
    EKORG,
    EKGRP,
    WAERS,
    TRY_CAST(BEDAT AS DATE) AS BEDAT
FROM raw_ekko;

CREATE OR REPLACE VIEW v_ekpo AS
SELECT
    EBELN,
    EBELP,
    LOEKZ,
    TXZ01,
    MATNR,
    WERKS,
    MATKL,
    TRY_CAST(REPLACE(MENGE, ',', '.') AS DECIMAL(18,4)) AS MENGE,
    MEINS,
    TRY_CAST(REPLACE(NETPR, ',', '.') AS DECIMAL(18,4)) AS NETPR,
    TRY_CAST(PEINH AS INTEGER) AS PEINH,
    TRY_CAST(REPLACE(NETWR, ',', '.') AS DECIMAL(18,4)) AS NETWR,
    KNTTP,
    BANFN,
    BNFPO,
    ELIKZ,
    EREKZ
FROM raw_ekpo;

CREATE OR REPLACE VIEW v_eban AS
SELECT
    BANFN,
    BNFPO,
    BSART,
    ESTKZ,
    STATU,
    LOEKZ,
    ERNAM,
    AFNAM,
    TRY_CAST(ERDAT AS DATE) AS ERDAT,
    TRY_CAST(BADAT AS DATE) AS BADAT,
    MATNR,
    TXZ01,
    MATKL,
    TRY_CAST(REPLACE(MENGE, ',', '.') AS DECIMAL(18,4)) AS MENGE,
    MEINS,
    TRY_CAST(REPLACE(PREIS, ',', '.') AS DECIMAL(18,4)) AS PREIS,
    TRY_CAST(PEINH AS INTEGER) AS PEINH,
    WAERS,
    TRY_CAST(LFDAT AS DATE) AS LFDAT,
    WERKS,
    EKGRP,
    LIFNR,
    KNTTP,
    FRGST,
    TRY_CAST(FRGDT AS DATE) AS FRGDT,
    EBELN,
    EBELP,
    TRY_CAST(BEDAT AS DATE) AS BEDAT,
    TRY_CAST(REPLACE(BSMNG, ',', '.') AS DECIMAL(18,4)) AS BSMNG,
    EBAKZ
FROM raw_eban;

CREATE OR REPLACE VIEW v_lfa1 AS SELECT * FROM raw_lfa1;
CREATE OR REPLACE VIEW v_mara AS SELECT * FROM raw_mara;
CREATE OR REPLACE VIEW v_t023t AS SELECT * FROM raw_t023t;

SELECT 'v_eban' AS vue, COUNT(*) AS nb_lignes FROM v_eban
UNION ALL SELECT 'v_ekko', COUNT(*) FROM v_ekko
UNION ALL SELECT 'v_ekpo', COUNT(*) FROM v_ekpo
UNION ALL SELECT 'v_lfa1', COUNT(*) FROM v_lfa1
UNION ALL SELECT 'v_mara', COUNT(*) FROM v_mara
UNION ALL SELECT 'v_t023t', COUNT(*) FROM v_t023t;