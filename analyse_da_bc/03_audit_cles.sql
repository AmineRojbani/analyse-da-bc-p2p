SELECT 'EBAN : BANFN + BNFPO' AS controle, COUNT(*) AS nb_doublons
FROM (
    SELECT BANFN, BNFPO
    FROM v_eban
    GROUP BY BANFN, BNFPO
    HAVING COUNT(*) > 1
)
UNION ALL
SELECT 'EKKO : EBELN', COUNT(*)
FROM (
    SELECT EBELN
    FROM v_ekko
    GROUP BY EBELN
    HAVING COUNT(*) > 1
)
UNION ALL
SELECT 'EKPO : EBELN + EBELP', COUNT(*)
FROM (
    SELECT EBELN, EBELP
    FROM v_ekpo
    GROUP BY EBELN, EBELP
    HAVING COUNT(*) > 1
)
UNION ALL
SELECT 'LFA1 : LIFNR', COUNT(*)
FROM (
    SELECT LIFNR
    FROM v_lfa1
    GROUP BY LIFNR
    HAVING COUNT(*) > 1
)
UNION ALL
SELECT 'MARA : MATNR', COUNT(*)
FROM (
    SELECT MATNR
    FROM v_mara
    GROUP BY MATNR
    HAVING COUNT(*) > 1
)
UNION ALL
SELECT 'T023T : MATKL', COUNT(*)
FROM (
    SELECT MATKL
    FROM v_t023t
    GROUP BY MATKL
    HAVING COUNT(*) > 1
);