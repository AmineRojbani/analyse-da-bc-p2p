SELECT 'EBAN.ERDAT hors 2024-10-01 / 2026-09-30' AS controle, COUNT(*) AS nb_lignes
FROM v_eban
WHERE ERDAT < DATE '2024-10-01' OR ERDAT > DATE '2026-09-30'
UNION ALL
SELECT 'EKKO.BEDAT hors 2024-10-01 / 2026-09-30', COUNT(*)
FROM v_ekko
WHERE BEDAT < DATE '2024-10-01' OR BEDAT > DATE '2026-09-30'
UNION ALL
SELECT 'EBAN.ERDAT vide', COUNT(*)
FROM v_eban
WHERE ERDAT IS NULL
UNION ALL
SELECT 'EBAN.ERDAT différent de BADAT', COUNT(*)
FROM v_eban
WHERE ERDAT <> BADAT
UNION ALL
SELECT 'EKKO.AEDAT différent de BEDAT', COUNT(*)
FROM v_ekko
WHERE AEDAT <> BEDAT
UNION ALL
SELECT 'EBAN.MENGE <= 0', COUNT(*)
FROM v_eban
WHERE MENGE <= 0
UNION ALL
SELECT 'EBAN.PREIS <= 0', COUNT(*)
FROM v_eban
WHERE PREIS <= 0
UNION ALL
SELECT 'EKPO.MENGE <= 0', COUNT(*)
FROM v_ekpo
WHERE MENGE <= 0
UNION ALL
SELECT 'EKPO.NETPR <= 0', COUNT(*)
FROM v_ekpo
WHERE NETPR <= 0
UNION ALL
SELECT 'EKPO.NETWR <= 0', COUNT(*)
FROM v_ekpo
WHERE NETWR <= 0
UNION ALL
SELECT 'EBAN.PEINH <= 0', COUNT(*)
FROM v_eban
WHERE PEINH <= 0
UNION ALL
SELECT 'EKPO.PEINH <= 0', COUNT(*)
FROM v_ekpo
WHERE PEINH <= 0
UNION ALL
SELECT 'EBAN.BSMNG supérieur à MENGE', COUNT(*)
FROM v_eban
WHERE BSMNG > MENGE
UNION ALL
SELECT 'EBAN.FRGDT avant ERDAT', COUNT(*)
FROM v_eban
WHERE FRGDT < ERDAT
UNION ALL
SELECT 'EBAN.LFDAT avant ERDAT', COUNT(*)
FROM v_eban
WHERE LFDAT < ERDAT;