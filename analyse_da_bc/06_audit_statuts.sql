SELECT 'EBAN.ESTKZ' AS colonne, COALESCE(ESTKZ, '(vide)') AS valeur, COUNT(*) AS nb_lignes
FROM v_eban GROUP BY ESTKZ
UNION ALL
SELECT 'EBAN.STATU', COALESCE(STATU, '(vide)'), COUNT(*)
FROM v_eban GROUP BY STATU
UNION ALL
SELECT 'EBAN.LOEKZ', COALESCE(LOEKZ, '(vide)'), COUNT(*)
FROM v_eban GROUP BY LOEKZ
UNION ALL
SELECT 'EBAN.EBAKZ', COALESCE(EBAKZ, '(vide)'), COUNT(*)
FROM v_eban GROUP BY EBAKZ
UNION ALL
SELECT 'EBAN.FRGST', COALESCE(FRGST, '(vide)'), COUNT(*)
FROM v_eban GROUP BY FRGST
UNION ALL
SELECT 'EBAN.BSART', COALESCE(BSART, '(vide)'), COUNT(*)
FROM v_eban GROUP BY BSART
UNION ALL
SELECT 'EKKO.BSART', COALESCE(BSART, '(vide)'), COUNT(*)
FROM v_ekko GROUP BY BSART
UNION ALL
SELECT 'EKKO.LOEKZ', COALESCE(LOEKZ, '(vide)'), COUNT(*)
FROM v_ekko GROUP BY LOEKZ
UNION ALL
SELECT 'EKPO.LOEKZ', COALESCE(LOEKZ, '(vide)'), COUNT(*)
FROM v_ekpo GROUP BY LOEKZ
ORDER BY colonne, valeur;